export type BankLayoutType = "centered" | "split-left" | "split-right" | "full-width";

export type BlockType = "header" | "form" | "footer" | "spacer";

export type BankElement = {
  id: string;
  type: "container" | "text" | "input" | "button" | "image" | "form";
  content?: string; 
  attributes?: Record<string, string>;
  styles: Record<string, string>;
  children?: BankElement[];
};

export type BankDesignConfig = {
  layout: BankLayoutType;
  blocks: BlockType[]; // For drag and drop ordering
  background: {
    type: "color" | "image";
    value: string; // HEX color or Image URL
  };
  header: {
    show: boolean;
    backgroundColor: string;
    height: string; // e.g., "80px", "100px"
    logoAlignment: "left" | "center" | "right";
    padding: string;
  };
  formBox: {
    backgroundColor: string;
    textColor: string;
    borderRadius: string; // e.g., "0px", "8px", "16px"
    boxShadow: string; // none, sm, md, lg
    padding: string; // e.g., "24px"
    width: string; // e.g., "400px", "100%"
    alignment: "left" | "center" | "right";
  };
  button: {
    backgroundColor: string;
    hoverColor: string;
    textColor: string;
    borderRadius: string;
    padding: string;
    fontWeight: string;
  };
  typography: {
    fontFamily: string; // e.g., "sans-serif", "serif"
    headerColor: string;
    bodyColor: string;
    linkColor: string;
  };
  texts: {
    title: string;
    subtitle: string;
    footerLinks: string[]; // e.g., ["Contact", "Privacy", "Veilig bankieren"]  
  };
  customCss?: string; // For any fine-tuning
  customHtml?: string; // Pure HTML/Tailwind template generated by AI for perfect pixel-to-pixel custom components
  visualTree?: BankElement; // Fully editable visual DOM tree
};

